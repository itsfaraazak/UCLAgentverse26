import type { EvalResults, MethodResult, VariantRow } from './benchmark';
import { af, ci, frac, pct, score } from './format';
import type { MethodMetrics } from './metrics';

function headlineRow(m: MethodResult): string {
  const o = m.overall;
  return `| ${m.name} | ${frac(o.coverage)} | ${frac(o.accuracy)} | ${frac(o.sensitivity)} | ${frac(o.specificity)} | **${String(o.falseReassurance.k)}** | ${String(o.falseAlarm.k)} |`;
}

function splitCell(x: MethodMetrics): string {
  return x.coverage.n === 0 ? 'n/a' : `${pct(x.coverage.value, 0)} / ${pct(x.accuracy.value, 0)} / ${String(x.falseReassurance.k)}`;
}

function caseLine(r: VariantRow, call: string): string {
  const link = r.clinvarUrl ? `[ClinVar](${r.clinvarUrl})` : 'ClinVar';
  return `- **${r.gene}** ${r.hgvs ?? r.id} (\`${r.id}\`, ${r.consequence}): ClinVar ${r.clinvarConsensus} (${String(r.stars)} stars, ${link}); called ${call}. AlphaMissense ${score(r.alphaMissense)}, gnomAD AF ${af(r.maxAf)}. SigmaFold: ${r.sigmafold.classification}.`;
}

export function evaluationMarkdown(r: EvalResults): string {
  const d = r.dataset;
  const sf = r.methods.find((m) => m.id === 'sigmafold')!;
  const am = r.methods.find((m) => m.id === 'alphamissense');
  const rc = r.sigmafold.referenceCheck;
  const sfo = sf.overall;
  const vus = sfo.n - sfo.coverage.k;
  const crit = r.sigmafold.criteriaFired;
  const lofCurated = r.sigmafold.lofPathogenicInCuratedGenes;

  const frSections = r.methods
    .map((m) => {
      const rows = r.falseReassurance[m.id] ?? [];
      return `**${m.name}** (${String(rows.length)}):${rows.length === 0 ? ' none.' : `\n\n${rows.map((x) => caseLine(x, 'B/LB')).join('\n')}`}`;
    })
    .join('\n\n');

  return `# Evaluation: SigmaFold against simple baselines on ClinVar expert consensus

_Generated by \`pnpm eval\` from \`src/data/eval/results.json\`. Do not edit by hand._

## What we tested

We took **${String(d.n)} real variants** whose clinical meaning has been settled by ClinVar at 2 stars or more (expert panel, or several labs agreeing with no conflicts): ${String(d.byTruth['P/LP'])} pathogenic or likely pathogenic (P/LP) and ${String(d.byTruth['B/LB'])} benign or likely benign (B/LB), spread over ${String(d.genes)} genes (at most ${String(d.maxPerGene)} per gene). ${String(d.byGroup.missense)} are missense changes and ${String(d.byGroup.lof)} are loss-of-function changes (stop-gain, frameshift, canonical splice). For each one we gave the classifier only the evidence the product shows it (gnomAD frequency, AlphaMissense, consequence), never the ClinVar answer, and compared its call with ClinVar's. We ran the same comparison for two one-signal baselines: AlphaMissense alone, and population frequency alone.

## Headline results

| Method | Coverage (made a P/LP or B/LB call) | Accuracy when it called | Sensitivity (P/LP found) | Specificity (B/LB found) | False reassurance (P/LP called B/LB) | False alarm (B/LB called P/LP) |
|---|---|---|---|---|---|---|
${r.methods.map(headlineRow).join('\n')}

Sensitivity and specificity count a VUS or no-call as a miss. Split by consequence (coverage / accuracy when called / false reassurance):

| Method | Missense (n=${String(sf.missense.n)}) | Loss of function (n=${String(sf.lof.n)}) |
|---|---|---|
${r.methods.map((m) => `| ${m.name} | ${splitCell(m.missense)} | ${splitCell(m.lof)} |`).join('\n')}
${r.omittedMethods.map((o) => `\nBaseline C (CADD alone) was not run. ${o.reason}`).join('')}

## What it means

- **${(sfo.accuracy.value ?? 0) >= 0.95 ? 'SigmaFold is right when it commits, but it rarely commits.' : 'SigmaFold rarely commits, and is not always right when it does.'}** It made a decisive call on ${frac(sfo.coverage)} variants; ${frac(sfo.accuracy)} of those agreed with ClinVar (${ci(sfo.accuracy)}), but those are the easy cases: common variants and truncating variants in well-known disease genes. It left **${String(vus)} variants (${pct(vus / sfo.n)}) as Uncertain Significance**. That low coverage is the real headline, and it follows from the design: the engine implements 8 of the ~28 ACMG/AMP criteria, so a missense variant can reach at most PM2 + PP3 = 3 points (VUS), and Likely Benign is unreachable by points. Benign calls only come from the BA1 frequency rule (fired ${String(crit.BA1 ?? 0)} times) and pathogenic calls only from PVS1 (fired ${String(crit.PVS1 ?? 0)} times; only ${frac(lofCurated)} of the pathogenic loss-of-function variants sit in its hand-curated gene list).
- **${sfo.falseReassurance.k === 0 ? 'No false reassurance from SigmaFold' : `${String(sfo.falseReassurance.k)} false-reassurance calls from SigmaFold`}** in this set (${String(sfo.falseReassurance.k)} of ${String(sfo.falseReassurance.n)} P/LP called benign), against ${String(am?.overall.falseReassurance.k ?? 0)} for AlphaMissense alone. Where AlphaMissense is wrong, SigmaFold uses the same score only as supporting evidence at stricter cut-offs (>= 0.7 / < 0.3, worth +1 / -1), so the error is absorbed into a VUS rather than becoming a confident wrong call.
- **AlphaMissense alone covers far more missense variants** (${am ? frac(am.missense.coverage) : 'n/a'}) at ${am ? frac(am.missense.accuracy) : 'n/a'} accuracy, but cannot score loss-of-function variants at all. Frequency alone can only argue benign and found ${frac(r.methods.find((m) => m.id === 'frequency')?.overall.specificity ?? sfo.specificity)} of benign variants.

## Would the product catch SigmaFold's mistakes?

In the workbench, a classification that lands on the other side of the actionable line from ClinVar (P/LP versus anything else) is a **major disagreement**, and merge is blocked until a human signs off with a rationale. On this set that path fires for **${String(rc.majorFlags)} of ${String(sfo.n)} variants**: ${rc.decisiveErrors === 0 ? 'SigmaFold made no confident wrong calls, so every flag is' : `${String(rc.decisiveErrorsFlagged)} of its ${String(rc.decisiveErrors)} confident wrong calls, plus`} ${String(rc.pathogenicAbstentionsFlagged)} of the ${String(rc.pathogenicAbstentions)} pathogenic variants it left at VUS. The other ${String(rc.benignAbstentionsUnflagged)} VUS calls are benign variants; they stay on the same side of the line, so they are recorded as minor and not escalated. This safety net only works when ClinVar already has a confident record; for a genuinely novel variant there is no reference to disagree with, and the VUS itself is the signal that a human must decide.

## False-reassurance cases

${frSections}

## Limitations and circularity

- **Agreement is partly circular.** ClinVar curators use gnomAD frequency and computational predictors as ACMG evidence, and the AlphaMissense thresholds (0.34 / 0.564) were calibrated against ClinVar labels. Agreement with ClinVar therefore measures consistency with expert curation, not clinical validity, and flatters every method that uses those same signals.
- **Easy cases are over-represented.** Variants with 2+ star consensus are, by construction, the ones experts could settle. Real diagnostic queues are dominated by rare missense VUS, where every method here would do worse.
- **Small sample.** ${String(d.n)} variants give wide confidence intervals (shown in \`results.json\`); differences of a few variants are not meaningful.
- **Scoped engine.** SigmaFold implements 8 of ~28 criteria with simplified PVS1 (consequence + curated gene list, no NMD or last-exon check). It is a demonstration of a transparent rule engine, not a certified clinical tool.
- **Sampling.** Candidates come from seeded random pages of MyVariant.info search results, not a uniform draw from all of ClinVar; benign loss-of-function variants are rare (${String(d.strata.find((s) => s.id === 'benign-lof')?.total ?? 0)} search hits in total) and may be atypical (for example last-exon or alternative-transcript changes).

## Dataset and licences

Real public reference data, not patient data. Fetched ${d.fetchedAt} from ${d.api} (assembly hg38) with the evidence service's own field list; sampling seed ${String(d.seed)}. Inclusion: ${d.inclusion}

${d.licences.map((l) => `- **${l.name}**: ${l.licence} (${l.licenceUrl})`).join('\n')}

Exact queries, page offsets and per-stratum counts are in \`src/data/eval/benchmark.json\` under \`provenance.strata\`.

## Reproduce

\`\`\`
pnpm eval         # offline: scores src/data/eval/benchmark.json, writes results.json and this file
pnpm eval:build   # live: re-samples the benchmark from MyVariant.info (results will shift as ClinVar updates)
\`\`\`

A judge-facing view of the same numbers is at \`/evaluation\` in the app.
`;
}
